function enrich(q: StarterQ): { question: Question; answers: Answer[] } {
  const answers: Answer[] = q.answersRaw.map((a) => ({
    ...a,
    questionId: q.id,
  }));
  const accepted = answers.find((a) => a.accepted);
  const { answersRaw: _raw, ...rest } = q;
  return {
    question: {
      ...rest,
      answers: answers.length,
      solved: Boolean(accepted),
      expert: accepted?.name ?? "",
      expertHandle: accepted?.handle,
    },
    answers,
  };
}

const enriched = starters.map(enrich);

export const STARTER_QUESTIONS: Question[] = enriched.map((e) => e.question);

export const STARTER_ANSWERS: Answer[] = enriched.flatMap((e) => e.answers);

export function getStarterQuestion(id: string) {
  return STARTER_QUESTIONS.find((q) => q.id === id);
}

export function getStarterAnswers(questionId: string) {
  return STARTER_ANSWERS.filter((a) => a.questionId === questionId);
}
