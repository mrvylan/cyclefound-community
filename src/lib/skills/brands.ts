const DROP = new Set([
  "sram-code",
  "colnago-c64",
  "formula-oro",
  "reynolds-wheels", // keep Reynolds tubing as Reynolds; wheels rarely tagged separately
  "easton-components", // ambiguous with Easton Tubing
]);

function dedupe(list: BrandSeed[]): BrandSeed[] {
  const byId = new Map<string, BrandSeed>();
  const byLabel = new Map<string, string>();
  for (const brand of list) {
    if (DROP.has(brand.id)) continue;
    if (byId.has(brand.id)) continue;
    const key = brand.label.toLowerCase();
    if (byLabel.has(key)) continue;
    byId.set(brand.id, brand);
    byLabel.set(key, brand.id);
  }
  return [...byId.values()].sort((a, b) => a.label.localeCompare(b.label, "en"));
}

export const BIKE_BRANDS: BrandSeed[] = dedupe(RAW);

export function brandCount() {
  return BIKE_BRANDS.length;
}
